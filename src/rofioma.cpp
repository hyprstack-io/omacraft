QString Rofioma::buttonId(const QJsonObject &button, int index) {
    QString id = button.value("id").toString().toLower();
    id.remove(QRegularExpression("[^a-z0-9-]"));
    return id.isEmpty() ? QString("button-%1").arg(index) : id;
}

QString Rofioma::wlogoutLayout(const QJsonObject &power, const QString &dir) {
    const bool labels = power.value("labels").toBool(true);
    QString out;
    int index = 0;
    for (const auto &value : power.value("buttons").toArray()) {
        const QJsonObject b = value.toObject();
        if (!b.value("enabled").toBool(true))
            continue;
        // wlogout wants a key for every button: its letter, or the id's first.
        QString key = b.value("key").toString().left(1).toLower();
        if (!QRegularExpression("^[a-z0-9]$").match(key).hasMatch())
            key = buttonId(b, index).left(1);
        const QJsonObject entry{{"label", buttonId(b, index)},
                                {"action", "sh " + Proc::shellQuote(dir + "/power.sh") + " run " + QString::number(index)},
                                {"text", labels ? b.value("label").toString() : QString()},
                                {"keybind", key}};
        out += QString::fromUtf8(QJsonDocument(entry).toJson(QJsonDocument::Indented)) + "\n";
        ++index;
    }
    return out;
}

QString Rofioma::wlogoutCss(const QJsonObject &power, const QVariantMap &p, const QJsonObject &look, const QString &dir) {
    QStringList ids;
    int index = 0;
    for (const auto &value : power.value("buttons").toArray()) {
        const QJsonObject b = value.toObject();
        if (b.value("enabled").toBool(true))
            ids << buttonId(b, index++);
    }
    // HyDE's proportions: hypr_border 10 gives a 50px hover radius and 80px
    // ends; here they follow the popups' radius (14 gives the same).
    const double radius = look.value("radius").toDouble(14);
    const QString active = px(radius * 50 / 14), ends = px(radius * 80 / 14);
    // The icon's share of the card at rest, focused and hovered (HyDE's 20,
    // 30 and 40%), scaled by the icon size.
    const double scale = power.value("glyphSize").toDouble(44) / 44;
    auto share = [scale](double percent) { return QString::number(qRound(percent * scale)) + "%"; };
    const QString font = look.value("font").toString("JetBrainsMono Nerd Font");
    const double opacity = look.value("opacity").toDouble(0.94);

    QString out = QString("/* %1 */\n\n"
                          "* {\n    background-image: none;\n    font-family: \"%2\";\n    font-size: @FONT@px;\n"
                          "    box-shadow: none;\n    text-shadow: none;\n}\n\n"
                          "window {\n    background-color: %3;\n}\n\n"
                          "button {\n    color: %4;\n    background-color: %5;\n    outline-style: none;\n"
                          "    border: none;\n    border-width: 0px;\n    background-repeat: no-repeat;\n"
                          "    background-position: center;\n    background-size: %6;\n    border-radius: 0px;\n"
                          "    margin: @MGN@px 0px;\n}\n\n"
                          "button:focus {\n    background-color: %7;\n    background-size: %8;\n}\n\n"
                          // The transition lives on :hover, as in HyDE: the card
                          // bounces open and snaps back when the pointer leaves.
                          "button:hover {\n    color: %9;\n    background-color: %10;\n    background-size: %11;\n"
                          "    border-radius: %12;\n    margin: @HVR@px 0px;\n"
                          "    transition: all 0.3s cubic-bezier(.55, 0.0, .28, 1.682);\n}\n")
                      .arg(header("Power menu"), font, rgba("#000000", power.value("dim").toDouble(0.55)),
                           p.value("fg").toString(), rgba(p.value("bg").toString(), opacity), share(20),
                           p.value("alt").toString(), share(30), p.value("accentFg").toString())
                      .arg(p.value("accent").toString(), share(40), active);

    for (int i = 0; i < ids.size(); ++i) {
        const QString &id = ids.at(i);
        const bool first = i == 0, last = i == ids.size() - 1;
        // The bar's ends are rounded and keep the screen-side margin.
        const QString rest = first && last ? "@MGN@px" : first ? "@MGN@px 0px @MGN@px @MGN@px"
                           : last ? "@MGN@px @MGN@px @MGN@px 0px" : "@MGN@px 0px";
        const QString hover = first && last ? "@HVR@px @MGN@px" : first ? "@HVR@px 0px @HVR@px @MGN@px"
                            : last ? "@HVR@px @MGN@px @HVR@px 0px" : "@HVR@px 0px";
        const QString corners = first && last ? ends : first ? ends + " 0px 0px " + ends
                              : last ? "0px " + ends + " " + ends + " 0px" : "0px";
        const QString icon = dir + "/wlogout/" + id;
        out += QString("\n#%1 {\n    background-image: url(\"%2.png\");\n    border-radius: %3;\n    margin: %4;\n}\n"
                       "#%1:hover {\n    background-image: url(\"%2-hover.png\");\n    border-radius: %5;\n    margin: %6;\n}\n")
                   .arg(id, icon, corners, rest, active, hover);
    }
    return out;
}

QByteArray Rofioma::wlogoutIcon(const QString &glyph, const QString &color) {
    // Big enough to stay sharp at 40% of a tall card on a 4K screen.
    constexpr int size = 256;
    QImage image(size, size, QImage::Format_ARGB32_Premultiplied);
    image.fill(Qt::transparent);
    QPainter painter(&image);
    painter.setRenderHint(QPainter::TextAntialiasing);
    QFont font;
    font.setFamilies({"JetBrainsMono Nerd Font", "Symbols Nerd Font Mono", "Symbols Nerd Font"});
    font.setPixelSize(int(size * 0.8));
    painter.setFont(font);
    painter.setPen(QColor(color));
    painter.drawText(QRect(0, 0, size, size), Qt::AlignCenter, glyph);
    painter.end();
    QByteArray png;
    QBuffer buffer(&png);
    buffer.open(QIODevice::WriteOnly);
    image.save(&buffer, "PNG");
    return png;
}

