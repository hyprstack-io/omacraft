void Rofioma::load() {
    QJsonObject saved;
    QFile file(configPath());
    if (file.open(QIODevice::ReadOnly))
        saved = QJsonDocument::fromJson(file.readAll()).object();
    // Anything new since the file was written comes from the defaults.
    QJsonObject config = defaults();
    for (auto it = saved.begin(); it != saved.end(); ++it) {
        if (it.value().isObject() && config.value(it.key()).isObject()) {
            QJsonObject section = config.value(it.key()).toObject();
            const QJsonObject mine = it.value().toObject();
            for (auto field = mine.begin(); field != mine.end(); ++field)
                section.insert(field.key(), field.value());
            config.insert(it.key(), section);
        } else {
            config.insert(it.key(), it.value());
        }
    }
    m_config = config;
}

void Rofioma::reload() {
    load();
    findTools();
    emit changed();
}

void Rofioma::findTools() {
    static const QList<QPair<QString, QString>> tools{
        {"rofi", "rofi"}, {"jq", "jq"}, {"wl-copy", "wl-clipboard"}, {"wtype", "wtype"}, {"swaync", "swaync"}};
    QVariantList missing;
    for (const auto &[program, package] : tools)
        if (Proc::which(program).isEmpty())
            missing << QVariantMap{{"program", program}, {"package", package}};
    if (missing != m_missing) {
        m_missing = missing;
        emit toolsChanged();
    }
}

QVariantMap Rofioma::palette() const {
    const QJsonObject look = m_config.value("look").toObject();
    QVariantMap base = look.value("colors").toString() == "custom" ? look.value("custom").toObject().toVariantMap()
                                                                  : themeColors(m_home);
    const QColor bg(base.value("bg").toString());
    const QColor fg(base.value("fg").toString());
    const QColor accent(base.value("accent").toString());
    QVariantMap out;
    out["bg"] = bg.name();
    out["fg"] = fg.name();
    out["accent"] = accent.name();
    out["urgent"] = QColor(base.value("urgent").toString()).name();
    out["alt"] = Theme::mix(bg, fg, 0.08).name();
    out["muted"] = Theme::mix(fg, bg, 0.42).name();
    out["accentFg"] = (Theme::contrastRatio(accent, QColor("#111111")) >= Theme::contrastRatio(accent, QColor("#f5f5f5"))
                           ? QColor("#111111") : QColor("#f5f5f5")).name();
    return out;
}

bool Rofioma::swayncOwns() const {
    QFile file(shellPath());
    if (!file.open(QIODevice::ReadOnly))
        return false;
    const auto disabled = QJsonDocument::fromJson(file.readAll()).object().value("disabledPlugins").toArray();
    return disabled.contains(QJsonValue(kShellPlugin));
}

QString Rofioma::slug(const QString &name) {
    QString out = name.toLower();
    out.replace(QRegularExpression("[^a-z0-9]+"), "-");
    out.remove(QRegularExpression("^-+|-+$"));
    return out.isEmpty() ? "menu" : out;
}

const QList<QStringList> &Rofioma::symbolRows(const QString &kind) const {
    const QString name = kind == "glyphs" ? "glyphs" : "emoji";
    if (!m_symbols.contains(name)) {
        QList<QStringList> rows;
        QFile data(":/data/" + name + ".tsv");
        if (data.open(QIODevice::ReadOnly))
            for (const QString &line : QString::fromUtf8(data.readAll()).split('\n', Qt::SkipEmptyParts))
                rows << line.split('\t');
        m_symbols.insert(name, rows);
    }
    return m_symbols[name];
}

QVariantList Rofioma::searchSymbols(const QString &kind, const QString &query, const QString &set, int limit) const {
    const QStringList words = query.toLower().split(' ', Qt::SkipEmptyParts);
    QVariantList out;
    for (const QStringList &row : symbolRows(kind)) {
        if (row.size() < 3 || (!set.isEmpty() && row.at(2) != set))
            continue;
        const QString code = QString::number(row.at(0).toUcs4().value(0), 16);
        const QString haystack = row.at(1) + " " + row.at(2).toLower() + " " + code;
        bool all = true;
        for (const QString &word : words)
            all = all && haystack.contains(word);
        if (!all)
            continue;
        out << QVariantMap{{"symbol", row.at(0)}, {"name", row.at(1)}, {"set", row.at(2)}, {"code", code.toUpper()}};
        if (out.size() >= limit)
            break;
    }
    return out;
}

QStringList Rofioma::symbolSets(const QString &kind) const {
    QStringList sets;
    for (const QStringList &row : symbolRows(kind))
        if (row.size() > 2 && !sets.contains(row.at(2)))
            sets << row.at(2);
    return sets;
}

void Rofioma::copy(const QString &text) {
    if (!m_runCommands)
        return;
    if (!Proc::detach("wl-copy", {text}))
        return setError("wl-copy isn't installed, so nothing was copied.");
    setNotice(text + "  copied.");
}

void Rofioma::refreshBinds() {
    if (!m_runCommands)
        return;
    Proc::run(this, "hyprctl", {"binds", "-j"}, [this](const Proc::Result &result) {
        static const QList<QPair<int, QString>> mods{{64, "SUPER"}, {4, "CTRL"}, {8, "ALT"}, {1, "SHIFT"}};
        QVariantList binds;
        for (const auto &value : QJsonDocument::fromJson(result.out).array()) {
            const QJsonObject bind = value.toObject();
            if (!bind.value("has_description").toBool() || bind.value("description").toString().isEmpty())
                continue;
            QStringList keys;
            for (const auto &[bit, name] : mods)
                if (bind.value("modmask").toInt() & bit)
                    keys << name;
            keys << bind.value("key").toString().toUpper();
            binds << QVariantMap{{"keys", keys.join(" + ")}, {"description", bind.value("description").toString()}};
        }
        m_binds = binds;
        emit bindsChanged();
    });
}

