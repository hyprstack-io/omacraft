bool Rofioma::editShell(bool swaync, QString *problem) {
    QFile file(shellPath());
    if (!file.open(QIODevice::ReadWrite)) {
        *problem = "Couldn't open " + shellPath() + ": " + file.errorString();
        return false;
    }
    const QByteArray before = file.readAll();
    QJsonParseError parseError;
    QJsonObject shell = before.trimmed().isEmpty() ? QJsonObject() : QJsonDocument::fromJson(before, &parseError).object();
    if (!before.trimmed().isEmpty() && parseError.error != QJsonParseError::NoError) {
        *problem = "shell.json isn't valid JSON, so it was left alone.";
        return false;
    }
    QJsonArray disabled = shell.value("disabledPlugins").toArray();
    for (int i = disabled.size() - 1; i >= 0; --i)
        if (disabled.at(i).toString() == kShellPlugin)
            disabled.removeAt(i);
    if (swaync)
        disabled << kShellPlugin;
    shell.insert("disabledPlugins", disabled);
    // In place, not through a rename: the shell's file watcher stays on it.
    const QByteArray bytes = QJsonDocument(shell).toJson(QJsonDocument::Indented);
    if (!file.seek(0) || file.write(bytes) != bytes.size() || !file.resize(bytes.size())) {
        *problem = "Couldn't save " + shellPath() + ": " + file.errorString();
        return false;
    }
    return true;
}

void Rofioma::handNotificationsToSwaync(bool on) {
    findTools();
    if (on && Proc::which("swaync").isEmpty() && m_runCommands)
        return setError("swaync isn't installed. Install the missing tools above, then try again.");
    QString problem;
    if (!editShell(on, &problem))
        return setError(problem);
    if (on) {
        QJsonObject notify = m_config.value("notify").toObject();
        notify.insert("manage", true);
        m_config.insert("notify", notify);
    }
    save(true);
    if (!m_runCommands)
        return;
    if (on) {
        // The shell lets go of the bus as it reloads; swaync takes it after.
        Proc::run(this, "omarchy-shell", {"shell", "reloadConfig"}, [this](const Proc::Result &) {
            QTimer::singleShot(1200, this, [] { Proc::detach("swaync", {}); });
        });
        setNotice("Notifications are swaync's now. The shell's own daemon is off until you take them back.");
    } else {
        Proc::run(this, "pkill", {"-x", "swaync"}, [this](const Proc::Result &) {
            Proc::detach("omarchy-shell", {"shell", "reloadConfig"});
        });
        setNotice("Notifications are back with the Omarchy shell.");
    }
}

void Rofioma::installMissing() {
    findTools();
    if (m_missing.isEmpty() || !m_runCommands)
        return;
    QStringList packages;
    for (const auto &tool : m_missing)
        packages << tool.toMap().value("package").toString();
    Proc::inTerminal("sudo pacman -S --needed " + packages.join(' ') + "; echo; read -n1 -rsp 'Done. Press any key to close.'");
    setNotice("Installing " + packages.join(", ") + " in a terminal. ROFIoma looks again when you come back.");
}

