// The shell lines that turn rofi's chosen row (by number) into a command.
QString caseArms(const QStringList &commands) {
    QString out;
    for (int i = 0; i < commands.size(); ++i) {
        // One line to an arm: a command written over several lines runs them in turn.
        const QString command = commands.at(i).trimmed().replace('\n', "; ");
        out += QString("    %1) %2 ;;\n").arg(i).arg(command.isEmpty() ? ":" : command);
    }
    return out;
}

QVariantMap themeColors(const QString &home) {
    const auto colors = Theme::readColors(home + "/.local/state/omarchy/current/theme/colors.toml");
    const bool dark = Theme::isDark(colors);
    auto named = [&](const char *key, const char *fallback) {
        const QColor c(colors.value(key));
        return c.isValid() ? c : QColor(fallback);
    };
    QVariantMap out;
    out["bg"] = named("background", dark ? "#121212" : "#f4f4f5").name();
    out["fg"] = named("foreground", dark ? "#e6e6e6" : "#18181b").name();
    out["accent"] = named("accent", "#ffd60a").name();
    out["urgent"] = named("red", "#e5534b").name();
    return out;
}

