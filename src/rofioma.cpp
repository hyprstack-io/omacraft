void Rofioma::set(const QString &path, const QVariant &value) {
    const QStringList parts = path.split('.');
    if (parts.size() < 2 || parts.size() > 3 || !m_config.value(parts.at(0)).isObject())
        return;
    QJsonObject section = m_config.value(parts.at(0)).toObject();
    const QJsonValue json = QJsonValue::fromVariant(value);
    if (parts.size() == 2) {
        if (section.value(parts.at(1)) == json)
            return;
        section.insert(parts.at(1), json);
    } else {
        QJsonObject inner = section.value(parts.at(1)).toObject();
        if (inner.value(parts.at(2)) == json)
            return;
        inner.insert(parts.at(2), json);
        section.insert(parts.at(1), inner);
    }
    m_config.insert(parts.at(0), section);
    save();
}

