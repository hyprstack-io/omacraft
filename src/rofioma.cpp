void Rofioma::open(const QString &popup) {
    findTools();
    // The files exist before the first open, even with nothing changed yet.
    if (!QFileInfo::exists(outputDir() + "/colors.rasi"))
        save();
    if (!m_runCommands)
        return;
    if (Proc::which("rofi").isEmpty())
        return setError("rofi isn't installed. Install the missing tools above, then try again.");
    QStringList arguments;
    if (popup == "emoji" || popup == "glyphs")
        arguments = {outputDir() + "/symbols.sh", popup};
    else
        arguments = {outputDir() + "/" + popup + ".sh"};
    if (!QFileInfo::exists(arguments.first()))
        return setError("There's no popup called " + popup + ".");
    Proc::detach("sh", arguments);
}

bool Rofioma::bindKey(const QString &popup, const QString &key) {
    // A key that failed before says nothing about this one.
    m_error.clear();
    QJsonObject keys = m_config.value("keys").toObject();
    // Only popups ROFIoma has: a typo would otherwise be saved and never bound.
    bool known = QStringList{"power", "emoji", "glyphs", "keybinds", "notifications"}.contains(popup);
    for (const auto &value : m_config.value("menus").toArray())
        known = known || popup == "menu-" + value.toObject().value("id").toString();
    if (!known && !key.trimmed().isEmpty()) {
        setError(QString("ROFIoma has no popup called \"%1\".").arg(popup));
        return false;
    }
    if (key.trimmed().isEmpty()) {
        keys.remove(popup);
    } else {
        const QString normalized = WallPicker::normalizeKey(key);
        if (normalized.isEmpty()) {
            setError(QString("\"%1\" isn't a key Hyprland can bind. Write it like SUPER + CTRL + ESCAPE.").arg(key.trimmed()));
            return false;
        }
        for (auto it = keys.begin(); it != keys.end(); ++it)
            if (it.key() != popup && it.value().toString().compare(normalized, Qt::CaseInsensitive) == 0) {
                setError(normalized + " already opens another ROFIoma popup.");
                return false;
            }
        keys.insert(popup, normalized);
    }
    m_config.insert("keys", keys);
    save(true);
    if (m_error.isEmpty())
        setNotice(key.trimmed().isEmpty() ? "Key removed." : "Bound " + keys.value(popup).toString() + ". Hyprland has reloaded.");
    return m_error.isEmpty();
}

void Rofioma::testNotification() {
    if (!m_runCommands)
        return;
    Proc::detach("notify-send", {"-u", "low", "-a", "ROFIoma", "Low urgency", "A quiet note that fades sooner."});
    Proc::detach("notify-send", {"-a", "ROFIoma", "-i", "dialog-information", "ROFIoma",
                                 "This is how your notifications look now."});
    Proc::detach("notify-send", {"-u", "critical", "-a", "ROFIoma", "Critical", "These stay until dismissed."});
}

bool Rofioma::editShell(bool swaync, QString *problem) {
    QFile file(shellPath());
    if (!file.open(QIODevice::ReadWrite)) {
        *problem = "Couldn't open " + shellPath() + ": " + file.errorString();
        return false;
    }
    const QByteArray before = file.readAll();
    QJsonParseError parseError;
    QJsonObject shell = before.trimmed().isEmpty() ? QJsonObject() : QJsonDocument::fromJson(before, &parseError).object();
    if (!before.trimmed().isEmpty() && parseError.error != QJsonParseError::NoError) {
        *problem = "shell.json isn't valid JSON, so it was left alone.";
        return false;
    }
    QJsonArray disabled = shell.value("disabledPlugins").toArray();
    for (int i = disabled.size() - 1; i >= 0; --i)
        if (disabled.at(i).toString() == kShellPlugin)
            disabled.removeAt(i);
    if (swaync)
        disabled << kShellPlugin;
    shell.insert("disabledPlugins", disabled);
    // In place, not through a rename: the shell's file watcher stays on it.
    const QByteArray bytes = QJsonDocument(shell).toJson(QJsonDocument::Indented);
    if (!file.seek(0) || file.write(bytes) != bytes.size() || !file.resize(bytes.size())) {
        *problem = "Couldn't save " + shellPath() + ": " + file.errorString();
        return false;
    }
    return true;
}

void Rofioma::handNotificationsToSwaync(bool on) {
    findTools();
    if (on && Proc::which("swaync").isEmpty() && m_runCommands)
        return setError("swaync isn't installed. Install the missing tools above, then try again.");
    QString problem;
    if (!editShell(on, &problem))
        return setError(problem);
    if (on) {
        QJsonObject notify = m_config.value("notify").toObject();
        notify.insert("manage", true);
        m_config.insert("notify", notify);
    }
    save(true);
    if (!m_runCommands)
        return;
    if (on) {
        // The shell lets go of the bus as it reloads; swaync takes it after.
        Proc::run(this, "omarchy-shell", {"shell", "reloadConfig"}, [this](const Proc::Result &) {
            QTimer::singleShot(1200, this, [] { Proc::detach("swaync", {}); });
        });
        setNotice("Notifications are swaync's now. The shell's own daemon is off until you take them back.");
    } else {
        Proc::run(this, "pkill", {"-x", "swaync"}, [this](const Proc::Result &) {
            Proc::detach("omarchy-shell", {"shell", "reloadConfig"});
        });
        setNotice("Notifications are back with the Omarchy shell.");
    }
}

void Rofioma::installMissing() {
    findTools();
    if (m_missing.isEmpty() || !m_runCommands)
        return;
    QStringList packages, aur;
    for (const auto &tool : m_missing)
        (tool.toMap().value("aur").toBool() ? aur : packages) << tool.toMap().value("package").toString();
    QStringList steps;
    if (!packages.isEmpty())
        steps << "sudo pacman -S --needed " + packages.join(' ');
    if (!aur.isEmpty())
        steps << "yay -S --needed " + aur.join(' ');
    Proc::inTerminal(steps.join("; ") + "; echo; read -n1 -rsp 'Done. Press any key to close.'");
    setNotice("Installing " + (packages + aur).join(", ") + " in a terminal. ROFIoma looks again when you come back.");
}

void Rofioma::setError(const QString &message) {
    m_error = message;
    m_notice.clear();
    emit messageChanged();
}

void Rofioma::setNotice(const QString &message) {
    m_notice = message;
    m_error.clear();
    emit messageChanged();
}

void Rofioma::dismissMessages() {
    m_error.clear();
    m_notice.clear();
    emit messageChanged();
}
