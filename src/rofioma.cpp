QString Rofioma::symbolsScript(const QJsonObject &symbols, const QString &dir) {
    const bool grid = symbols.value("layout").toString("grid") == "grid";
    const QString action = symbols.value("action").toString("copy");
    const bool recents = symbols.value("recents").toBool(true);
    // A grid shows the symbol large with its name small beneath; a list
    // shows both on one line. Names are escaped for Pango as they're read.
    const QString format = grid ? R"(printf "%s&#10;<span font_size=\"42%%\" alpha=\"60%%\">%s</span>\n", $1, n)"
                                : R"(printf "<span font_size=\"130%%\">%s</span>   %s  <span alpha=\"50%%\">%s</span>\n", $1, n, g)";
    QString deliver;
    if (action == "copy" || action == "both")
        deliver += "printf '%s' \"$symbol\" | wl-copy\n";
    if (action == "type" || action == "both")
        deliver += "sleep 0.15; wtype \"$symbol\"\n";
    if (action == "copy")
        deliver += "notify-send -t 1500 \"$symbol copied\" 2>/dev/null || true\n";

    return QString("#!/bin/sh\n# %1\n# symbols.sh emoji|glyphs\ndir=%2\n"
                   "kind=${1:-emoji}\n"
                   "list=\"$dir/$kind.tsv\"\n"
                   "recent=\"${XDG_CACHE_HOME:-$HOME/.cache}/omacraft/rofioma-$kind-recent\"\n"
                   "mkdir -p \"$(dirname \"$recent\")\"; touch \"$recent\"\n"
                   "pkill -x rofi && exit 0\n\n"
                   "rows=$(mktemp); trap 'rm -f \"$rows\"' EXIT\n"
                   "%3"
                   "cat \"$list\" >> \"$rows\"\n\n"
                   "prompt=$([ \"$kind\" = glyphs ] && echo ' Glyphs' || echo '󰞅 Emoji')\n"
                   "choice=$(awk -F '\\t' '{ n=$2; g=$3; gsub(/&/, \"\\\\&amp;\", n); gsub(/</, \"\\\\&lt;\", n);\n"
                   "    gsub(/&/, \"\\\\&amp;\", g); gsub(/</, \"\\\\&lt;\", g); %4 }' \"$rows\" \\\n"
                   "    | rofi -dmenu -i -markup-rows -no-custom -format i%7 -p \"$prompt\" -theme \"$dir/symbols.rasi\")\n"
                   "[ -n \"$choice\" ] || exit 0\n"
                   "symbol=$(sed -n \"$((choice + 1))p\" \"$rows\" | cut -f1)\n"
                   "[ -n \"$symbol\" ] || exit 0\n\n"
                   "%5"
                   "%6")
        .arg(header("Symbols"), Proc::shellQuote(dir),
             recents ? "# The most recent picks first, each still searchable by name.\n"
                       "tab=$(printf '\\t')\n"
                       "while IFS= read -r used; do grep -m1 -F \"$used$tab\" \"$list\"; done < \"$recent\" > \"$rows\"\n"
                     : ": > \"$rows\"\n",
             format,
             recents ? "{ echo \"$symbol\"; grep -v -x -F \"$symbol\" \"$recent\"; } | head -n 24 > \"$recent.new\" && mv \"$recent.new\" \"$recent\"\n"
                     : "",
             deliver, grid ? " -eh 2" : "");
}

