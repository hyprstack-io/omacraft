QString Rofioma::menuScript(const QJsonObject &menu, const QString &dir, bool overlay) {
    const QString layout = menu.value("layout").toString("list");
    const QString id = menu.value("id").toString();
    QStringList entries, commands;
    for (const auto &value : menu.value("items").toArray()) {
        const QJsonObject item = value.toObject();
        const QString glyph = item.value("glyph").toString();
        const QString label = markup(item.value("label").toString());
        if (layout == "list")
            entries << (glyph.isEmpty() ? label : glyphSpan(glyph, {}) + "   " + label);
        else
            entries << glyphSpan(glyph, "200%") + "&#10;" + label;
        commands << item.value("command").toString();
    }
    const QString prompt = menu.value("prompt").toString(menu.value("name").toString());
    // exec <n>: the overlay picked item n.
    return QString("#!/bin/sh\n# %1\ndir=%2\n\n"
                   "if [ \"${1:-}\" = exec ]; then\n"
                   "    choice=${2:-}\n"
                   "else\n%7"
                   "    pkill -x rofi && exit 0\n"
                   "    choice=$(printf '%s\\n' %3 | rofi -dmenu -i -markup-rows -no-custom -format i -p %4 \\\n"
                   "        -theme \"$dir/menu-%5.rasi\")\n"
                   "fi\n"
                   "[ -n \"$choice\" ] || exit 0\n\n"
                   "case \"$choice\" in\n%6esac\n")
        .arg(header(menu.value("name").toString()), Proc::shellQuote(dir), Proc::shellQuote(entries.join('\n')),
             Proc::shellQuote(prompt), id, caseArms(commands), overlay ? overlayLine("menu-" + id, "    ") : QString());
}

