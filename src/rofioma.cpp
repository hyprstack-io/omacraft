QVariantList Rofioma::bindsFrom(const QByteArray &json, const QJsonObject &keymap, bool describedOnly) {
    static const QList<QPair<int, QString>> mods{{64, "SUPER"}, {1, "SHIFT"}, {4, "CTRL"}, {8, "ALT"}};
    // Where each moved bind came from, by the keys it's on now.
    QHash<QString, QString> from;
    for (auto it = keymap.begin(); it != keymap.end(); ++it)
        from.insert(canonicalKeys(it.value().toString()), it.key());
    QVariantList binds;
    for (const auto &value : QJsonDocument::fromJson(json).array()) {
        const QJsonObject bind = value.toObject();
        const QString description = bind.value("description").toString();
        if (describedOnly && (!bind.value("has_description").toBool() || description.isEmpty()))
            continue;
        if (bind.value("mouse").toBool())
            continue;
        QStringList keys;
        for (const auto &[bit, name] : mods)
            if (bind.value("modmask").toInt() & bit)
                keys << name;
        const QString key = bind.value("key").toString();
        // Letters upper case, names (XF86AudioMute, Return) as Hyprland spells them.
        keys << (key.isEmpty() ? QString("code:%1").arg(bind.value("keycode").toInt())
                               : key.size() == 1 ? key.toUpper() : key);
        const QString joined = keys.join(" + ");
        binds << QVariantMap{{"keys", joined}, {"description", description},
                             {"submap", bind.value("submap").toString()},
                             {"dispatcher", bind.value("dispatcher").toString()}, {"arg", bind.value("arg").toString()},
                             {"movedFrom", from.value(canonicalKeys(joined))}};
    }
    return binds;
}

// ---------------------------------------------------------------- moved keys

QString Rofioma::canonicalKeys(const QString &keys) { return WallPicker::normalizeKey(keys).toUpper(); }

QString Rofioma::keymapLua(const QJsonObject &keymap) {
    QString moved;
    for (auto it = keymap.begin(); it != keymap.end(); ++it) {
        const QString source = canonicalKeys(it.key()), target = WallPicker::normalizeKey(it.value().toString());
        // normalizeKey lets no quote or backslash through, so they quote as is.
        if (!source.isEmpty() && !target.isEmpty())
            moved += "  [\"" + source + "\"] = \"" + target + "\",\n";
    }
    return "-- " + header("Keybinds") + "\n"
           "-- Loaded ahead of Omarchy's binds. A bind declared on keys listed here is\n"
           "-- declared on the keys it was moved to instead, so it keeps its action.\n\n"
           "local moved = {\n" + moved + "}\n\n"
           "-- While OmaCraft waits for a new key, this submap holds no binds, so the\n"
           "-- key that's pressed reaches it instead of running. CTRL + ALT + ESCAPE\n"
           "-- leaves it, should OmaCraft not.\n"
           "hl.define_submap(\"omacraft_capture\", function()\n"
           "  hl.bind(\"CTRL + ALT + ESCAPE\", hl.dsp.submap(\"reset\"))\n"
           "end)\n\n"
           "if next(moved) == nil then return end\n\n"
           // The same canonical form as OmaCraft's: modifiers in this order,
           // whatever their alias, then the key, all upper case.
           "local order = { \"SUPER\", \"SHIFT\", \"CTRL\", \"ALT\" }\n"
           "local alias = { SUPER = \"SUPER\", WIN = \"SUPER\", META = \"SUPER\", MOD4 = \"SUPER\", LOGO = \"SUPER\",\n"
           "                SHIFT = \"SHIFT\", CTRL = \"CTRL\", CONTROL = \"CTRL\", ALT = \"ALT\" }\n\n"
           "local function canonical(keys)\n"
           "  if type(keys) ~= \"string\" then return nil end\n"
           "  local mods, key = {}, \"\"\n"
           "  for part in keys:gmatch(\"[^%s+]+\") do\n"
           "    local up = part:upper()\n"
           "    if alias[up] then mods[alias[up]] = true else key = up end\n"
           "  end\n"
           "  local out = {}\n"
           "  for _, name in ipairs(order) do\n"
           "    if mods[name] then out[#out + 1] = name end\n"
           "  end\n"
           "  out[#out + 1] = key\n"
           "  return table.concat(out, \" + \")\n"
           "end\n\n"
           "local function target(keys)\n"
           "  return moved[canonical(keys)] or keys\n"
           "end\n\n"
           "local bind, unbind = hl.bind, hl.unbind\n"
           "hl.bind = function(keys, ...) return bind(target(keys), ...) end\n"
           "hl.unbind = function(keys, ...) return unbind(target(keys), ...) end\n";
}

QByteArray Rofioma::currentBindsJson() const {
    if (!m_runCommands)
        return {};
    QProcess process;
    process.start("hyprctl", {"binds", "-j"});
    if (!process.waitForFinished(3000))
        return {};
    return process.readAllStandardOutput();
}

QString Rofioma::moveBind(const QString &from, const QString &to) {
    const QString current = canonicalKeys(from);
    if (current.isEmpty())
        return "Can't read the keys \"" + from + "\".";
    QString target;
    if (!to.trimmed().isEmpty()) {
        target = WallPicker::normalizeKey(to);
        if (target.isEmpty())
            return "\"" + to + "\" isn't a key Hyprland can bind. Write it like SUPER + SHIFT + K.";
    }
    QJsonObject keymap = m_config.value("keymap").toObject();
    // The bind's own keys: where Hyprland first declares it, if it has
    // been moved before.
    QString original = current;
    for (auto it = keymap.begin(); it != keymap.end(); ++it)
        if (canonicalKeys(it.value().toString()) == current)
            original = canonicalKeys(it.key());
    // No new keys puts it back where it started.
    const QString destination = target.isEmpty() ? original : target;
    if (canonicalKeys(destination) == current)
        return {};
    // Two binds on the same keys would both run; the keys must be free.
    for (const auto &value : bindsFrom(currentBindsJson(), keymap, false)) {
        const QVariantMap bind = value.toMap();
        if (bind.value("submap").toString().isEmpty() && canonicalKeys(bind.value("keys").toString()) == canonicalKeys(destination)) {
            const QString what = bind.value("description").toString();
            return destination + " is already taken" + (what.isEmpty() ? QString(".") : " by " + what + ".")
                   + " Move that one first.";
        }
    }
    for (auto it = keymap.begin(); it != keymap.end();)
        it = canonicalKeys(it.key()) == original ? keymap.erase(it) : std::next(it);
    if (canonicalKeys(destination) != original)
        keymap.insert(original, destination);
    m_config.insert("keymap", keymap);
    save();
    if (!writeKeymap())
        return m_error;
    refreshBinds();
    setNotice(canonicalKeys(destination) == original ? "Back on " + destination + "." : "Moved to " + destination + ".");
    return {};
}

bool Rofioma::writeKeymap() {
    QString problem;
    if (!Proc::writeAtomically(keymapPath(), keymapLua(m_config.value("keymap").toObject()).toUtf8(), &problem)) {
        setError("Can't write " + keymapPath() + ": " + problem);
        return false;
    }
    // It has to load before Omarchy declares its binds, so its line goes
    // just above Omarchy's own require (or at the very top without one).
    const QString main = m_home + "/.config/hypr/hyprland.lua";
    QFile file(main);
    QString contents;
    if (file.open(QIODevice::ReadOnly))
        contents = QString::fromUtf8(file.readAll());
    file.close();
    const QString line = "pcall(require, \"hypr.omacraft_keymap\") -- OmaCraft's moved keys; must stay above Omarchy's binds\n";
    if (!contents.contains("hypr.omacraft_keymap")) {
        if (QFileInfo::exists(main))
            QFile::copy(main, QString("%1.before-keymap-%2").arg(main).arg(QDateTime::currentSecsSinceEpoch()));
        const int at = contents.indexOf(QRegularExpression("^\\s*require\\(\"default\\.hypr\\.omarchy\"\\)", QRegularExpression::MultilineOption));
        contents.insert(at < 0 ? 0 : at, line);
        if (!Proc::writeAtomically(main, contents.toUtf8(), &problem)) {
            setError("Can't add the moved keys to " + main + ": " + problem);
            return false;
        }
    }
    if (m_runCommands)
        Proc::detach("hyprctl", {"reload"});
    return true;
}

void Rofioma::captureKeys(bool on) {
    if (!m_runCommands)
        return;
    const QString submap = on ? "omacraft_capture" : "reset";
    const QString dispatch = "hl.dispatch(hl.dsp.submap(\"" + submap + "\"))";
    // The submap lives in the keymap file; the first capture writes it, and
    // the submap is entered once Hyprland has reloaded.
    if (on && !QFileInfo::exists(keymapPath())) {
        if (!writeKeymap())
            return;
        QTimer::singleShot(600, this, [dispatch] { Proc::detach("hyprctl", {"eval", dispatch}); });
        return;
    }
    Proc::detach("hyprctl", {"eval", dispatch});
}

