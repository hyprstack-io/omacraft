QString px(double value) { return QString::number(qRound(value)) + "px"; }

// #rrggbbaa, which rofi and GTK CSS both take.
QString withAlpha(const QString &hex, double alpha) {
    return QColor(hex).name(QColor::HexRgb) + QString("%1").arg(qRound(qBound(0.0, alpha, 1.0) * 255), 2, 16, QChar('0'));
}

QString rgba(const QString &hex, double alpha) {
    const QColor c(hex);
    return QString("rgba(%1, %2, %3, %4)").arg(c.red()).arg(c.green()).arg(c.blue()).arg(qBound(0.0, alpha, 1.0));
}

QString markup(QString text) {
    return text.replace('&', "&amp;").replace('<', "&lt;").replace('>', "&gt;");
}

// A rofi string: double quoted, with its own escapes.
QString rasiString(QString text) { return '"' + text.replace('\\', "\\\\").replace('"', "\\\"") + '"'; }

// An icon glyph in Pango markup, always in the Nerd Font: the popups' own
// font may have no icons, and whatever fontconfig falls back to can sit too
// big or off centre in its card.
QString glyphSpan(const QString &glyph, const QString &size) {
    QString attrs = "font_family=\"JetBrainsMono Nerd Font\"";
    if (!size.isEmpty())
        attrs += " font_size=\"" + size + "\"";
    return "<span " + attrs + ">" + markup(glyph) + "</span>";
}

// The line a popup's script starts with: the omacraft.rofioma overlay
// draws it when the shell has that plugin enabled (summon says "ok"), and
// otherwise the script carries on to rofi.
QString overlayLine(const QString &popup, const QString &indent) {
    const QString payload = QString::fromUtf8(
        QJsonDocument(QJsonObject{{"popup", popup}, {"toggle", true}}).toJson(QJsonDocument::Compact));
    return indent + "[ \"$(omarchy-shell shell summon omacraft.rofioma " + Proc::shellQuote(payload) +
           " 2>/dev/null)\" = ok ] && exit 0\n";
}

QString header(const QString &what) {
    return QString("Generated by OmaCraft (ROFIoma › %1). Edit it there; changes here are overwritten.").arg(what);
}

// The window every popup opens in: a dimmed full screen with the panel in the
// middle, or just the panel.
QString windowBlock(double width, double dim, const QJsonObject &look, bool panel) {
    const double radius = look.value("radius").toDouble(14);
    const double border = look.value("border").toDouble(2);
    QString out = "window {\n";
    if (dim > 0.001) {
        out += "    fullscreen: true;\n";
        out += QString("    background-color: %1;\n").arg(rgba("#000000", dim));
    } else {
        out += QString("    width: %1;\n").arg(px(width));
        out += "    location: center;\n    anchor: center;\n";
        out += panel ? "    background-color: @rf-bg;\n" : "    background-color: transparent;\n";
        if (panel) {
            out += QString("    border: %1;\n    border-color: @rf-accent;\n").arg(px(border));
            out += QString("    border-radius: %1;\n").arg(px(radius));
        }
    }
    out += "}\n";
    return out;
}

// In a dimmed full screen, boxes either side of the content keep it centred,
// on a panel or (panel false) straight on the dimmed screen.
QString centredMainbox(double dim, double width, const QJsonObject &look, const QString &content, bool panel = true) {
    if (dim <= 0.001)
        return QString("mainbox {\n    children: [ %1 ];\n    padding: 18px;\n    spacing: 12px;\n}\n").arg(content);
    const double radius = look.value("radius").toDouble(14);
    const double border = look.value("border").toDouble(2);
    return QString("mainbox {\n    orientation: vertical;\n    children: [ box-top, box-row, box-bottom ];\n}\n"
                   "box-top, box-bottom { expand: true; }\n"
                   "box-row {\n    expand: false;\n    orientation: horizontal;\n    children: [ box-left, box-panel, box-right ];\n}\n"
                   "box-left, box-right { expand: true; }\n"
                   "box-panel {\n    expand: false;\n    width: %1;\n    orientation: vertical;\n    children: [ %2 ];\n"
                   "    padding: 18px;\n    spacing: 12px;\n%3}\n")
        .arg(px(width), content,
             panel ? QString("    background-color: @rf-bg;\n    border: %1;\n    border-color: @rf-accent;\n    border-radius: %2;\n")
                         .arg(px(border), px(radius))
                   : QString());
}

