void Rofioma::open(const QString &popup) {
    findTools();
    // The files exist before the first open, even with nothing changed yet.
    if (!QFileInfo::exists(outputDir() + "/colors.rasi"))
        save();
    if (!m_runCommands)
        return;
    if (Proc::which("rofi").isEmpty())
        return setError("rofi isn't installed. Install the missing tools above, then try again.");
    QStringList arguments;
    if (popup == "emoji" || popup == "glyphs")
        arguments = {outputDir() + "/symbols.sh", popup};
    else
        arguments = {outputDir() + "/" + popup + ".sh"};
    if (!QFileInfo::exists(arguments.first()))
        return setError("There's no popup called " + popup + ".");
    Proc::detach("sh", arguments);
}

bool Rofioma::bindKey(const QString &popup, const QString &key) {
    // A key that failed before says nothing about this one.
    m_error.clear();
    QJsonObject keys = m_config.value("keys").toObject();
    if (key.trimmed().isEmpty()) {
        keys.remove(popup);
    } else {
        const QString normalized = WallPicker::normalizeKey(key);
        if (normalized.isEmpty()) {
            setError(QString("\"%1\" isn't a key Hyprland can bind. Write it like SUPER + CTRL + ESCAPE.").arg(key.trimmed()));
            return false;
        }
        for (auto it = keys.begin(); it != keys.end(); ++it)
            if (it.key() != popup && it.value().toString().compare(normalized, Qt::CaseInsensitive) == 0) {
                setError(normalized + " already opens another ROFIoma popup.");
                return false;
            }
        keys.insert(popup, normalized);
    }
    m_config.insert("keys", keys);
    save(true);
    if (m_error.isEmpty())
        setNotice(key.trimmed().isEmpty() ? "Key removed." : "Bound " + keys.value(popup).toString() + ". Hyprland has reloaded.");
    return m_error.isEmpty();
}

