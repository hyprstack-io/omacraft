QHash<QString, QByteArray> Rofioma::render() const {
    QHash<QString, QByteArray> files;
    const QString dir = outputDir();
    const QString rel = QDir(m_home).relativeFilePath(dir);
    const QJsonObject look = m_config.value("look").toObject();
    const QJsonObject power = m_config.value("power").toObject();
    const QJsonObject symbols = m_config.value("symbols").toObject();
    const QVariantMap p = palette();

    files[rel + "/colors.rasi"] = colorsRasi(p, look).toUtf8();
    files[rel + "/power.rasi"] = powerRasi(power, look).toUtf8();
    files[rel + "/confirm.rasi"] = confirmRasi(look).toUtf8();
    // The overlay draws the popups unless the look says rofi.
    const bool overlay = look.value("engine").toString("shell") != "rofi";
    files[rel + "/popups.json"] = popupsJson(m_config, p, dir);
    files[rel + "/power.sh"] = powerScript(power, dir, overlay).toUtf8();
    files[rel + "/wlogout/layout"] = wlogoutLayout(power, dir).toUtf8();
    files[rel + "/wlogout/style.css"] = wlogoutCss(power, p, look, dir).toUtf8();
    int index = 0;
    for (const auto &value : power.value("buttons").toArray()) {
        const QJsonObject b = value.toObject();
        if (!b.value("enabled").toBool(true))
            continue;
        const QString icon = rel + "/wlogout/" + buttonId(b, index++);
        files[icon + ".png"] = wlogoutIcon(b.value("glyph").toString(), p.value("fg").toString());
        files[icon + "-hover.png"] = wlogoutIcon(b.value("glyph").toString(), p.value("accentFg").toString());
    }
    files[rel + "/symbols.rasi"] = symbolsRasi(symbols, look).toUtf8();
    files[rel + "/symbols.sh"] = symbolsScript(symbols, dir).toUtf8();
    files[rel + "/keybinds.rasi"] = keybindsRasi(look).toUtf8();
    files[rel + "/notifications.sh"] = notificationsScript().toUtf8();
    files[rel + "/keybinds.sh"] = keybindsScript(dir, m_config.value("keybinds").toObject().value("run").toBool(true), overlay).replace("%RF_ACCENT%", p.value("accent").toString()).toUtf8();
    for (const auto &value : m_config.value("menus").toArray()) {
        const QJsonObject menu = value.toObject();
        const QString id = menu.value("id").toString();
        files[rel + "/menu-" + id + ".rasi"] = menuRasi(menu, look).toUtf8();
        files[rel + "/menu-" + id + ".sh"] = menuScript(menu, dir, overlay).toUtf8();
    }
    for (const char *list : {"emoji.tsv", "glyphs.tsv"}) {
        QFile data(QString(":/data/") + list);
        if (data.open(QIODevice::ReadOnly))
            files[rel + "/" + list] = data.readAll();
    }

    const QJsonObject notify = m_config.value("notify").toObject();
    if (notify.value("manage").toBool()) {
        const QString sway = QDir(m_home).relativeFilePath(swayncDir());
        files[sway + "/style.css"] = swayncCss(p, notify, look).toUtf8();
        files[sway + "/config.json"] = swayncConfig(notify);
    }
    return files;
}

void Rofioma::save(bool keysToo) {
    QString problem;
    if (!Proc::writeAtomically(configPath(), QJsonDocument(m_config).toJson(QJsonDocument::Indented), &problem))
        return setError("Can't save " + configPath() + ": " + problem);

    // swaync's own files are kept as they were, once, before the first write.
    const QString marker = outputDir() + "/.swaync-kept";
    const auto files = render();
    if (m_config.value("notify").toObject().value("manage").toBool() && !QFileInfo::exists(marker)) {
        const QString stamp = QString::number(QDateTime::currentSecsSinceEpoch());
        for (const char *name : {"style.css", "config.json"}) {
            const QString path = swayncDir() + "/" + name;
            if (QFileInfo::exists(path))
                QFile::copy(path, path + ".before-omacraft-" + stamp);
        }
        Proc::writeAtomically(marker, stamp.toUtf8());
    }

    bool swayncChanged = false;
    for (auto it = files.begin(); it != files.end(); ++it) {
        const QString path = m_home + "/" + it.key();
        QFile existing(path);
        if (existing.open(QIODevice::ReadOnly) && existing.readAll() == it.value())
            continue;
        existing.close();
        if (!Proc::writeAtomically(path, it.value(), &problem))
            return setError("Can't write " + path + ": " + problem);
        if (path.endsWith(".sh"))
            QFile::setPermissions(path, QFile::permissions(path) | QFile::ExeOwner | QFile::ExeUser);
        swayncChanged = swayncChanged || path.startsWith(swayncDir());
    }
    // Menus that were removed leave nothing behind.
    for (const QString &name : QDir(outputDir()).entryList({"menu-*"}, QDir::Files))
        if (!files.contains(QDir(m_home).relativeFilePath(outputDir() + "/" + name)))
            QFile::remove(outputDir() + "/" + name);

    if (keysToo)
        writeKeys();
    if (swayncChanged && m_runCommands && swayncOwns()) {
        Proc::detach("swaync-client", {"--reload-config"});
        Proc::detach("swaync-client", {"--reload-css"});
    }
    emit changed();
}

bool Rofioma::writeKeys() {
    QString problem;
    if (!Proc::writeAtomically(keysPath(), keysLua(m_config, outputDir(), swayncOwns()).toUtf8(), &problem)) {
        setError("Can't write " + keysPath() + ": " + problem);
        return false;
    }
    // hyprland.lua loads the file once; the line goes in a single time.
    const QString main = m_home + "/.config/hypr/hyprland.lua";
    QFile file(main);
    if (file.open(QIODevice::ReadOnly)) {
        const QByteArray contents = file.readAll();
        file.close();
        if (!contents.contains(kRequire)) {
            QFile::copy(main, QString("%1.before-rofioma-%2").arg(main).arg(QDateTime::currentSecsSinceEpoch()));
            if (!file.open(QIODevice::Append)) {
                setError("Can't add ROFIoma's keys to " + main + ": " + file.errorString());
                return false;
            }
            file.write(QString("\n-- ROFIoma's popup keys, set in OmaCraft.\npcall(require, \"%1\")\n").arg(kRequire).toUtf8());
        }
    }
    if (m_runCommands)
        Proc::detach("hyprctl", {"reload"});
    return true;
}

