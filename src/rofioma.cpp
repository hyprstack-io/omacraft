QJsonObject Rofioma::menu(const QString &id, int *index) const {
    const QJsonArray menus = m_config.value("menus").toArray();
    for (int i = 0; i < menus.size(); ++i)
        if (menus.at(i).toObject().value("id").toString() == id) {
            if (index)
                *index = i;
            return menus.at(i).toObject();
        }
    if (index)
        *index = -1;
    return {};
}

