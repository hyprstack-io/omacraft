QString Rofioma::keysLua(const QJsonObject &config, const QString &dir, bool swaync) {
    QString out = "-- " + header("Keys") + "\n";
    const QJsonObject keys = config.value("keys").toObject();
    auto names = QMap<QString, QString>{{"power", "Power menu"}, {"emoji", "Emoji picker"},
                                        {"glyphs", "Glyph picker"}, {"keybinds", "Keybinding cheatsheet"},
                                        {"notifications", "Notification control centre"}};
    for (const auto &value : config.value("menus").toArray()) {
        const QJsonObject menu = value.toObject();
        names.insert("menu-" + menu.value("id").toString(), menu.value("name").toString());
    }
    for (auto it = keys.begin(); it != keys.end(); ++it) {
        const QString key = WallPicker::normalizeKey(it.value().toString());
        if (key.isEmpty() || !names.contains(it.key()))
            continue;
        const QString popup = it.key();
        const QString script = popup == "emoji" || popup == "glyphs" ? "symbols.sh " + popup : popup + ".sh";
        QString command = "sh " + Proc::shellQuote(dir + "/" + script.section(' ', 0, 0));
        if (script.contains(' '))
            command += " " + script.section(' ', 1);
        QString description = names.value(popup);
        description.replace('\\', "\\\\").replace('"', "\\\"");
        command.replace('\\', "\\\\").replace('"', "\\\"");
        out += QString("hl.unbind(\"%1\")\no.bind(\"%1\", \"%2\", \"%3\")\n").arg(key, description, command);
    }
    if (swaync)
        out += "\n-- Notifications are swaync's (ROFIoma › Notifications).\no.launch_on_start(\"swaync\")\n";
    return out;
}

// ---------------------------------------------------------------- overlay

QByteArray Rofioma::popupsJson(const QJsonObject &config, const QVariantMap &palette, const QString &dir) {
    // Only what's drawn: the commands stay in the scripts, which the overlay
    // runs as `<script> exec <n>`, n counting the shown entries.
    QJsonObject power = config.value("power").toObject();
    QJsonArray buttons;
    for (const auto &value : power.value("buttons").toArray()) {
        QJsonObject b = value.toObject();
        if (!b.value("enabled").toBool(true))
            continue;
        b.remove("command");
        buttons << b;
    }
    power.insert("buttons", buttons);
    QJsonArray menus;
    for (const auto &value : config.value("menus").toArray()) {
        QJsonObject menu = value.toObject();
        QJsonArray items;
        for (const auto &item : menu.value("items").toArray()) {
            QJsonObject entry = item.toObject();
            entry.remove("command");
            items << entry;
        }
        menu.insert("items", items);
        menus << menu;
    }
    return QJsonDocument(QJsonObject{{"version", 1},
                                     {"dir", dir},
                                     {"palette", QJsonObject::fromVariantMap(palette)},
                                     {"look", config.value("look")},
                                     {"power", power},
                                     {"menus", menus},
                                     {"keybinds", config.value("keybinds")},
                                     {"keymap", config.value("keymap").toObject()}})
        .toJson(QJsonDocument::Indented);
}

