QString Rofioma::powerRasi(const QJsonObject &power, const QJsonObject &look) {
    const QString style = power.value("style").toString("row");
    const double size = power.value("size").toDouble(150);
    const double spacing = power.value("spacing").toDouble(14);
    const double radius = look.value("radius").toDouble(14);
    const double dim = style == "list" ? 0 : power.value("dim").toDouble(0.55);
    int count = 0;
    for (const auto &button : power.value("buttons").toArray())
        count += button.toObject().value("enabled").toBool(true) ? 1 : 0;
    count = qMax(1, count);

    const int columns = style == "grid" ? qMin(3, count) : style == "list" ? 1 : count;
    const int lines = style == "grid" ? (count + 2) / 3 : style == "list" ? count : 1;
    const double cell = style == "pill" ? size * 0.5 : size;
    const double cellHeight = style == "row" ? size * 1.15 : style == "list" ? 0 : cell;
    const double width = style == "list" ? 320 : columns * cell + (columns - 1) * spacing + 36;

    QString out = QString("/* %1 */\n@import \"colors.rasi\"\n\n").arg(header("Power menu"));
    out += windowBlock(width, dim, look, true);
    out += centredMainbox(dim, width, look, "listview", false);
    out += QString("listview {\n    columns: %1;\n    lines: %2;\n    fixed-columns: true;\n    fixed-height: true;\n"
                   "    spacing: %3;\n    cycle: true;\n    scrollbar: false;\n    layout: vertical;\n}\n")
               .arg(columns).arg(lines).arg(px(spacing));
    if (style == "list") {
        out += QString("element {\n    padding: 10px 14px;\n    spacing: 12px;\n    border-radius: %1;\n}\n").arg(px(radius * 0.6));
        out += "element-text {\n    vertical-align: 0.5;\n    text-color: inherit;\n}\n";
    } else {
        out += QString("element {\n    orientation: vertical;\n    padding: 0;\n    border-radius: %1;\n"
                       "    background-color: @rf-alt;\n    width: %2;\n    height: %3;\n}\n")
                   .arg(px(style == "pill" ? cell / 2 : radius), px(cell), px(cellHeight));
        out += "element-text {\n    horizontal-align: 0.5;\n    vertical-align: 0.5;\n    expand: true;\n    text-color: inherit;\n}\n";
    }
    out += "element normal.normal, element alternate.normal { background-color: " +
           QString(style == "list" ? "transparent" : "@rf-alt") + "; text-color: @rf-fg; }\n";
    out += "element selected.normal {\n    background-color: @rf-accent;\n    text-color: @rf-accent-fg;\n}\n";
    if (style != "list")
        out += QString("element selected.normal { border-radius: %1; }\n").arg(px(style == "pill" ? cell / 2 : radius * 1.8));

    return out;
}

QString Rofioma::powerScript(const QJsonObject &power, const QString &dir) {
    const QString style = power.value("style").toString("row");
    const bool labels = power.value("labels").toBool(true) && style != "pill";
    const int glyphSize = qRound(power.value("glyphSize").toInt(44) * (style == "pill" ? 0.6 : style == "list" ? 0.45 : 1.0));

    QStringList entries, commands, keys, confirms;
    for (const auto &value : power.value("buttons").toArray()) {
        const QJsonObject b = value.toObject();
        if (!b.value("enabled").toBool(true))
            continue;
        const QString glyph = QString("<span font_size=\"%1pt\">%2</span>").arg(glyphSize).arg(markup(b.value("glyph").toString()));
        const QString label = markup(b.value("label").toString());
        entries << (!labels ? glyph : style == "list" ? glyph + "   " + label : glyph + "\r" + label);
        commands << b.value("command").toString();
        keys << b.value("key").toString().left(1).toLower();
        confirms << (b.value("confirm").toBool() ? b.value("label").toString() : QString());
    }

    QString keyArgs;
    for (int i = 0; i < keys.size() && i < 10; ++i)
        if (!keys.at(i).isEmpty() && QRegularExpression("^[a-z0-9]$").match(keys.at(i)).hasMatch())
            keyArgs += QString(" -kb-select-%1 %2").arg(i + 1).arg(keys.at(i));

    QString confirmArms;
    for (int i = 0; i < confirms.size(); ++i)
        if (!confirms.at(i).isEmpty())
            confirmArms += QString("    %1) ask %2 || exit 0 ;;\n").arg(i).arg(Proc::shellQuote(confirms.at(i)));

    QString entryList = entries.join('\n');
    // A two-line card: rofi splits rows on newlines, so the card's own line
    // break travels as \r and becomes a newline in the markup.
    entryList.replace('\r', "&#10;");

    return QString("#!/bin/sh\n# %1\ndir=%2\n\n"
                   "ask() {\n"
                   "    answer=$(printf 'Yes\\nNo\\n' | rofi -dmenu -i -no-custom -p \"$1?\" -theme \"$dir/confirm.rasi\")\n"
                   "    [ \"$answer\" = Yes ]\n}\n\n"
                   "pkill -x rofi && exit 0\n"
                   "choice=$(printf '%s\\n' %3 | rofi -dmenu -markup-rows -no-custom -format i -p Power \\\n"
                   "    -theme \"$dir/power.rasi\"%4)\n"
                   "[ -n \"$choice\" ] || exit 0\n\n"
                   "case \"$choice\" in\n%5esac\n\n"
                   "case \"$choice\" in\n%6esac\n")
        .arg(header("Power menu"), Proc::shellQuote(dir), Proc::shellQuote(entryList), keyArgs, confirmArms,
             caseArms(commands));
}

