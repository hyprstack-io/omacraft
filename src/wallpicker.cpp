namespace {

const QStringList kModifiers{"SUPER", "SHIFT", "CTRL", "ALT"};
constexpr const char *kRequire = "hypr.omacraft_wallpicker";

QString modifierName(const QString &part) {
    const QString upper = part.toUpper();
    if (upper == "WIN" || upper == "META" || upper == "MOD4" || upper == "LOGO")
        return "SUPER";
    if (upper == "CONTROL")
        return "CTRL";
    return kModifiers.contains(upper) ? upper : QString();
}

} // namespace

WallPicker::WallPicker(const QString &home, bool runCommands, std::function<QString()> pluginDir, QObject *parent)
    : QObject(parent), m_home(home.isEmpty() ? QDir::homePath() : home), m_runCommands(runCommands),
      m_pluginDir(std::move(pluginDir)) {
    reload();
}

QVariantList WallPicker::cardEffects() {
    const QList<std::array<const char *, 3>> effects{
        {"trace", "Border Trace", "Two comets in the window border's colours chase round it, as in Burn My Windows"},
        {"orbit", "Orbit", "Four short comets circling quickly"},
        {"rainbow", "Rainbow", "One long comet going through every hue, leaving its colour on the edge"},
        {"pulse", "Pulse", "The border breathes between the two colours, swelling as it brightens"},
        {"neon", "Neon", "A bright line in a soft glow that slowly swells"},
        {"marching", "Marching", "Dashes in the two colours marching round"},
        {"plain", "Plain", "A still border in the first colour"},
    };
    QVariantList out;
    for (const auto &[id, name, description] : effects)
        out << QVariantMap{{"id", id}, {"name", name}, {"description", description}};
    return out;
}

QString WallPicker::cardBorderUrl() const {
    const QString dir = m_pluginDir ? m_pluginDir() : QString();
    const QString path = dir + "/CardBorder.qml";
    return !dir.isEmpty() && QFileInfo::exists(path) ? QUrl::fromLocalFile(path).toString() : QString();
}

void WallPicker::setCardEffect(const QString &id) {
    bool known = false;
    for (const auto &effect : cardEffects())
        known = known || effect.toMap().value("id").toString() == id;
    if (!known || id == m_cardEffect)
        return;
    m_cardEffect = id;
    saveSettings();
}

void WallPicker::setCardSpeed(double speed) {
    speed = qBound(0.25, speed, 3.0);
    if (qFuzzyCompare(speed, m_cardSpeed))
        return;
    m_cardSpeed = speed;
    saveSettings();
}

void WallPicker::setShowTitle(bool on) {
    if (on == m_showTitle)
        return;
    m_showTitle = on;
    saveSettings();
}

void WallPicker::saveSettings() {
    // In place, not through a rename: the picker's FileView would lose the
    // file it watches. Keys this doesn't know are kept.
    QJsonObject settings;
    QFile file(settingsPath());
    if (file.open(QIODevice::ReadOnly)) {
        settings = QJsonDocument::fromJson(file.readAll()).object();
        file.close();
    }
    settings.insert("cardEffect", m_cardEffect);
    settings.insert("cardSpeed", m_cardSpeed);
    settings.insert("showTitle", m_showTitle);
    QDir().mkpath(QFileInfo(settingsPath()).absolutePath());
    if (!file.open(QIODevice::WriteOnly | QIODevice::Truncate)) {
        setError("Can't write " + settingsPath() + ": " + file.errorString());
        return;
    }
    file.write(QJsonDocument(settings).toJson(QJsonDocument::Indented));
    m_error.clear();
    emit changed();
}

QString WallPicker::normalizeKey(const QString &key) {
    const QStringList parts = key.split(QRegularExpression("[+\\s]+"), Qt::SkipEmptyParts);
    QStringList modifiers;
    QString main;
    for (const QString &part : parts) {
        const QString modifier = modifierName(part);
        if (!modifier.isEmpty()) {
            if (!modifiers.contains(modifier))
                modifiers << modifier;
            continue;
        }
        // One key besides the modifiers, written as Hyprland's own bindings
        // write it: letters upper case, names (comma, code:201) as given.
        if (!main.isEmpty())
            return {};
        static const QRegularExpression name("^(code:\\d+|[A-Za-z0-9_]+|[^\\s\"\\\\])$");
        if (!name.match(part).hasMatch())
            return {};
        main = part.size() == 1 ? part.toUpper() : part;
    }
    if (main.isEmpty())
        return {};
    // In Hyprland's usual order, whatever order they were typed in.
    QStringList ordered;
    for (const QString &modifier : kModifiers)
        if (modifiers.contains(modifier))
            ordered << modifier;
    ordered << main;
    return ordered.join(" + ");
}

QString WallPicker::keysFile(const QString &key) {
    // normalizeKey lets no quote or backslash through, so it quotes as is.
    const QString quoted = '"' + key + '"';
    return QString("-- Generated by OmaCraft (Wallpapers › Picker key). Edit the key there.\n"
                   "-- Opens the omacraft.wallpicker overlay: the theme's backgrounds, a Wallhaven\n"
                   "-- search, the library and favourites, without OmaCraft's window. The key\n"
                   "-- opens it on the library; the arrows move to the other tabs.\n"
                   "hl.unbind(%1)\n"
                   "o.bind(%1, \"Wallpaper picker\", \"omarchy-shell shell toggle %2 '{\\\"tab\\\":\\\"library\\\"}'\")\n")
        .arg(quoted, kPluginId);
}

QString WallPicker::keyIn(const QString &file) {
    static const QRegularExpression bind("^o\\.bind\\(\"([^\"]+)\"", QRegularExpression::MultilineOption);
    const auto match = bind.match(file);
    return match.hasMatch() ? match.captured(1) : QString();
}

void WallPicker::reload() {
    QFile file(keysPath());
    m_key = file.open(QIODevice::ReadOnly) ? keyIn(QString::fromUtf8(file.readAll())) : QString();
    QFile settingsFile(settingsPath());
    const QJsonObject settings = settingsFile.open(QIODevice::ReadOnly)
                                     ? QJsonDocument::fromJson(settingsFile.readAll()).object() : QJsonObject();
    m_cardEffect = settings.value("cardEffect").toString("trace");
    const double speed = settings.value("cardSpeed").toDouble(1.0);
    m_cardSpeed = speed > 0 ? qBound(0.25, speed, 3.0) : 1.0;
    m_showTitle = settings.value("showTitle").toBool(true);
    emit changed();
}

bool WallPicker::bind(const QString &key) {
    const QString normalized = normalizeKey(key);
    if (normalized.isEmpty()) {
        setError(QString("\"%1\" isn't a key Hyprland can bind. Write it like %2.").arg(key.trimmed(), defaultKey()));
        return false;
    }
    if (!write(keysFile(normalized)))
        return false;

    // hyprland.lua loads the file once; the line goes in a single time.
    const QString main = m_home + "/.config/hypr/hyprland.lua";
    QFile file(main);
    if (file.open(QIODevice::ReadOnly)) {
        const QByteArray contents = file.readAll();
        file.close();
        if (!contents.contains(kRequire)) {
            QFile::copy(main, QString("%1.before-wallpicker-%2").arg(main).arg(QDateTime::currentSecsSinceEpoch()));
            if (!file.open(QIODevice::Append)) {
                setError("Can't add the picker key to " + main + ": " + file.errorString());
                return false;
            }
            file.write(QString("\n-- The wallpaper picker's key, set in OmaCraft.\npcall(require, \"%1\")\n").arg(kRequire).toUtf8());
        }
    }
    if (m_runCommands)
        Proc::detach("hyprctl", {"reload"});
    m_error.clear();
    m_key = normalized;
    emit changed();
    return true;
}

void WallPicker::unbind() {
    // The file stays (hyprland.lua still loads it), with nothing bound.
    if (!write("-- Generated by OmaCraft (Wallpapers › Picker key). No key is set.\n"))
        return;
    if (m_runCommands)
        Proc::detach("hyprctl", {"reload"});
    m_error.clear();
    m_key.clear();
    emit changed();
}

QStringList WallPicker::summonArguments(const QString &tab) {
    const QString payload = QString::fromUtf8(QJsonDocument(QJsonObject{{"tab", tab}}).toJson(QJsonDocument::Compact));
    return {"shell", "summon", kPluginId, payload};
}

void WallPicker::open(const QString &tab) {
    if (!m_runCommands)
        return;
    Proc::run(this, "omarchy-shell", summonArguments(tab), [this](const Proc::Result &result) {
        if (!result.ok() || result.out.trimmed() == "false")
            setError("The picker didn't open. Install and enable it above, then try again.");
    });
}

bool WallPicker::write(const QString &contents) {
    QString message;
    if (!Proc::writeAtomically(keysPath(), contents.toUtf8(), &message)) {
        setError("Can't write " + keysPath() + ": " + message);
        return false;
    }
    return true;
}

void WallPicker::setError(const QString &message) {
    m_error = message;
    emit changed();
}
