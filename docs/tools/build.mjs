#!/usr/bin/env node
// Builds the page's data from the repository itself, so the site shows what
// GitHub shows: run it after committing, before pushing.
//
//   node docs/tools/build.mjs
//
// Writes docs/assets/js/repo.js (files, last commit, languages, README,
// version) and docs/assets/js/flf-index.js (the FIGlet fonts in
// docs/assets/fonts/flf, which are copied from omascii's figlet.js).
import { execFileSync } from "node:child_process";
import { copyFileSync, readdirSync, readFileSync, statSync, writeFileSync, mkdirSync } from "node:fs";
import { dirname, extname, join } from "node:path";
import { fileURLToPath } from "node:url";

const DOCS = join(dirname(fileURLToPath(import.meta.url)), "..");
const ROOT = join(DOCS, "..");
const git = (...args) => execFileSync("git", ["-C", ROOT, ...args], { encoding: "utf8" }).trim();

// ── FIGlet fonts: keep docs' copy in step with omascii's ─────────────
const FLF_SRC = join(ROOT, "plugins", "omascii", "vendor", "figlet", "fonts");
const FLF = join(DOCS, "assets", "fonts", "flf");
mkdirSync(FLF, { recursive: true });
for (const f of readdirSync(FLF_SRC)) if (f.endsWith(".flf")) copyFileSync(join(FLF_SRC, f), join(FLF, f));
const flf = readdirSync(FLF).filter((f) => f.endsWith(".flf")).map((f) => f.slice(0, -4))
  .sort((a, b) => a.localeCompare(b, "en", { sensitivity: "base" }));
writeFileSync(join(DOCS, "assets", "js", "flf-index.js"),
  `// Generated by docs/tools/build.mjs. Don't edit by hand.\nwindow.OMA_FLF = ${JSON.stringify(flf)};\n`);

// ── the repository ────────────────────────────────────────────
const remote = git("remote", "get-url", "origin");
const m = /github\.com[:/]([^/]+)\/([^/.]+)/.exec(remote) || [null, "hyprstack-io", "omacraft"];
const [owner, name] = [m[1], m[2]];
const head = "HEAD";
const top = git("ls-tree", head, "--name-only").split("\n").filter(Boolean);
const types = Object.fromEntries(git("ls-tree", head).split("\n").filter(Boolean).map((l) => {
  const [meta, path] = l.split("\t");
  return [path, meta.split(" ")[1] === "tree" ? "dir" : "file"];
}));
const files = top.map((path) => {
  const [hash, date, subject] = git("log", "-1", "--format=%h%x09%cI%x09%s", head, "--", path).split("\t");
  return { name: path, type: types[path], hash, date, subject };
}).sort((a, b) => (a.type === b.type ? a.name.localeCompare(b.name) : a.type === "dir" ? -1 : 1));

const [hash, date, subject, author] = git("log", "-1", "--format=%h%x09%cI%x09%s%x09%an", head).split("\t");
const count = Number(git("rev-list", "--count", head));
const tags = git("tag", "--sort=-creatordate").split("\n").filter(Boolean);
const tagDate = tags[0] ? git("log", "-1", "--format=%cI", tags[0]) : null;

// Languages by bytes, as GitHub's linguist would count the main ones.
const LANG = {
  ".cpp": "C++", ".h": "C++", ".qml": "QML", ".js": "JavaScript", ".mjs": "JavaScript", ".py": "Python",
  ".sh": "Shell", ".css": "CSS", ".html": "HTML", ".lua": "Lua", ".frag": "GLSL", ".vert": "GLSL", ".pro": "QMake",
};
const COLOURS = {
  "C++": "#f34b7d", QML: "#44a51c", JavaScript: "#f1e05a", Python: "#3572A5", Shell: "#89e051", CSS: "#663399",
  HTML: "#e34c26", Lua: "#000080", GLSL: "#5686a5", QMake: "#c4a7e7", Other: "#8b949e",
};
const bytes = {};
for (const path of git("ls-files").split("\n")) {
  if (!path || path.startsWith("docs/") || path.includes("/vendor/") || path.includes("/fonts/")) continue;
  let lang = LANG[extname(path)];
  if (!lang && path.startsWith("bin/")) lang = "Shell";
  if (!lang) continue;
  try { bytes[lang] = (bytes[lang] || 0) + statSync(join(ROOT, path)).size; } catch { /* deleted */ }
}
const total = Object.values(bytes).reduce((a, b) => a + b, 0) || 1;
let languages = Object.entries(bytes).map(([n, b]) => ({ name: n, pct: (b / total) * 100, color: COLOURS[n] }))
  .sort((a, b) => b.pct - a.pct);
const small = languages.filter((l) => l.pct < 0.8);
languages = languages.filter((l) => l.pct >= 0.8);
if (small.length) languages.push({ name: "Other", pct: small.reduce((a, l) => a + l.pct, 0), color: COLOURS.Other });

// README, without the parts that only make sense on GitHub itself.
const readme = readFileSync(join(ROOT, "README.md"), "utf8").replace(/<!-- site:skip -->[\s\S]*?<!-- \/site:skip -->\n*/g, "");
const version = readFileSync(join(ROOT, "VERSION"), "utf8").trim();

const repo = { owner, name, url: `https://github.com/${owner}/${name}`, version, commit: { hash, date, subject, author, count },
  release: tags[0] ? { tag: tags[0], date: tagDate } : null, files, languages, readme };
writeFileSync(join(DOCS, "assets", "js", "repo.js"),
  `// Generated by docs/tools/build.mjs from the repository. Don't edit by hand.\nwindow.OMA_REPO = ${JSON.stringify(repo)};\n`);
console.log(`repo.js: ${files.length} entries, ${languages.length} languages, ${count} commits; flf-index.js: ${flf.length} fonts`);
